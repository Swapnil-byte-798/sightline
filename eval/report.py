#: See the note beside the same constant in :mod:`eval.selectivity`:
#: ``CorpusSpec`` is slotted, so its class attributes are descriptors.
_SPEC_DEFAULTS = CorpusSpec()

#: Managed regions, in the order they are written into the document.
BLOCKS: tuple[str, ...] = ("headline", "mutation", "selectivity", "attack", "provenance")

_BEGIN = "<!-- sightline:begin:{name} -->"
_END = "<!-- sightline:end:{name} -->"
_DATA_OPEN = "<!-- sightline:data"
_DATA_CLOSE = "-->"
# Everything up to the first comment close after the opener. Matching balanced
# braces instead would be a regex that breaks the day somebody nests an object in
# the payload; JSON cannot contain "-->" outside a string, and this payload has no
# strings, so the comment terminator is the reliable boundary.
_DATA_RE = re.compile(
    re.escape(_DATA_OPEN) + r"\s*(.*?)\s*" + re.escape(_DATA_CLOSE), re.S
)


# --------------------------------------------------------------------------
# Gates
# --------------------------------------------------------------------------


@dataclass(frozen=True, slots=True)
class Gate:
    """A tolerance rule for one metric key, or for a family of them.

    A key ending in ``*`` matches by prefix. Rules are checked most-specific
    first, so a family tolerance can be overridden for one member without
    reordering the table.
    """

    key: str
    tolerance: float
    why: str

    def matches(self, name: str) -> bool:
        return name.startswith(self.key[:-1]) if self.key.endswith("*") else name == self.key


#: Ordered for readability; matching is by specificity, not by position.
GATES: tuple[Gate, ...] = (
    Gate("mutation.killed", 0.0, "the headline numerator. Deterministic."),
    Gate("mutation.scored", 0.0, "the headline denominator. A change means a mutant stopped applying."),
    Gate("mutation.kill_rate", 0.0, "the headline metric."),
    Gate("attack.leaks", 0.0, "the only acceptable value is 0."),
    Gate("attack.passed", 0.0, "an attack that stops passing is a regression, not noise."),
    Gate("attack.false_allow", 0.0, "a plan admitting what check() denies is a breach."),
    Gate("reindex.*", 0.0, "vector writes per membership change. Expected exactly 0 (ADR 0002)."),
    Gate("selectivity.cost.*", 0.0, "distance computations are deterministic given the seed."),
    Gate("selectivity.recall.*", 0.02, "the drift tolerance published in docs/FRD.md 8.3."),
    Gate("selectivity.returned.*", 0.02, "mean results returned; same tolerance as recall."),
)

#: Prefix for numbers written into the README but deliberately not gated.
UNGATED_PREFIX = "_ungated."


def gate_for(name: str) -> Gate | None:
    """The tolerance rule governing ``name``, most specific first."""
    if name.startswith(UNGATED_PREFIX):
        return None
    candidates = [g for g in GATES if g.matches(name)]
    if not candidates:
        return None
    return max(candidates, key=lambda g: len(g.key))


@dataclass(frozen=True, slots=True)
class Drift:
    """One committed number that no longer matches a fresh run."""

    key: str
    committed: float | None
    fresh: float | None
    tolerance: float
    why: str

    @property
    def delta(self) -> float | None:
        if self.committed is None or self.fresh is None:
            return None
        return self.fresh - self.committed

    def __str__(self) -> str:
        if self.committed is None:
            return f"{self.key}: not in the README (fresh run says {self.fresh})"
        if self.fresh is None:
            return f"{self.key}: committed as {self.committed} but the fresh run produced nothing"
        return (
            f"{self.key}: README says {self.committed}, fresh run says {self.fresh} "
            f"(delta {self.delta:+.4g}, tolerance {self.tolerance:g}) — {self.why}"
        )


# --------------------------------------------------------------------------
# The reindex-cost measurement
# --------------------------------------------------------------------------


@dataclass(frozen=True, slots=True)
class ReindexCost:
    """What each kind of permission change costs the vector index.

    ADR 0002's central claim is that a person joining or leaving a group rewrites
    **zero vectors**, because chunks are tagged with tokens derived from groups
    and never with user ids. This measures the claim rather than restating it: it
    compares every document's compiled grant-token set before and after each kind
    of write, and a document whose token set is unchanged needs no vector
    rewritten.

    The measurement is on the tokens, not on a call counter. Counting calls to
    ``reindex_object`` would only prove that the harness did not call it.
    """

    documents: int
    documents_retokenised_on_membership_change: int
    documents_retokenised_on_acl_change: int

    @property
    def vectors_per_membership_change(self) -> int:
        """Zero, or ADR 0002 is wrong. Expressed in documents, one chunk each."""
        return self.documents_retokenised_on_membership_change


def measure_reindex_cost() -> ReindexCost:
    """Compare grant-token sets across a membership write and an ACL write."""
    tuples = [
        "group:eng#member@user:alice",
        "group:fin#member@user:bob",
        "doc:a#viewer@group:eng#member",
        "doc:b#viewer@group:eng#member",
        "doc:c#viewer@group:fin#member",
    ]
    docs = [ObjectRef("doc", i) for i in ("a", "b", "c")]
    store = MemoryTupleStore(tuples)

    def snapshot() -> dict[str, frozenset[str]]:
        return {str(d): frozenset(map(str, grant_tokens_for_object(store, d))) for d in docs}

    before = snapshot()

    # A membership change: somebody joins a group. Nothing about any document's
    # own ACL has changed, so no token set may move.
    store.write("group:eng#member@user:carol")
    after_membership = snapshot()
    membership_changed = sum(1 for d in before if before[d] != after_membership[d])

    # An ACL change: one document is shared with another group. Exactly that
    # document's token set must move, and the vector write it causes is the cost
    # the design accepts.
    store.write("doc:a#viewer@group:fin#member")
    after_acl = snapshot()
    acl_changed = sum(1 for d in after_membership if after_membership[d] != after_acl[d])

    return ReindexCost(
        documents=len(docs),
        documents_retokenised_on_membership_change=membership_changed,
        documents_retokenised_on_acl_change=acl_changed,
    )


