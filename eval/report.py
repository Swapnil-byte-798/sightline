"""Machine-write every published number into the README, and fail the build when
a committed one drifts.

The premise is narrow and it is the whole reason the numbers in this repository
are worth anything: **a figure typed into a README by hand is a claim, and a
figure regenerated by CI and diffed against the committed one is a measurement.**
Everything between the ``sightline:begin`` and ``sightline:end`` markers is
generated. Editing it by hand is not forbidden; it is simply undone by the next
run, and ``--check`` fails the build in the meantime.

    python -m eval.report            # run everything, rewrite the managed blocks
    python -m eval.report --check    # run everything, compare, exit non-zero on drift

CI runs ``--check``. A drifting number is a failing build, not a stale document
(FR-25).

WHAT IS GATED AND WHAT IS NOT
-----------------------------
Not every number deserves the same tolerance, and pretending otherwise produces
a gate that is either useless or permanently red.

* **Exact, zero tolerance.** The mutation kill rate and its numerator and
  denominator. The leak count. False allows from the plan/authority oracle.
  Vector writes per membership change. Distance computations per query. These
  are deterministic given the seed: any movement at all is a real change and
  should be looked at, not averaged away.
* **±0.02.** Recall figures, matching the drift tolerance in ``docs/FRD.md``
  §8.3. Recall here is deterministic too, but the tolerance is what the FRD
  published and moving it silently would be exactly the sin this file exists to
  prevent.
* **Not gated at all.** Wall-clock latency. It is written into the README
  because "how fast" is a fair question, and it is *not* gated because this
  repository is developed on a 2015 dual-core laptop that throttles, and a build
  that fails when the machine is warm teaches everybody to ignore the build.
  Ungated numbers are labelled as such in the README rather than quietly
  excluded — an ungated number presented next to gated ones, with no mark, is a
  lie of formatting.

CONCURRENCY AND OTHER PEOPLE'S PROSE
------------------------------------
This writes into a README somebody else maintains. It therefore only ever
touches the region between its own markers, and when the markers are absent it
inserts the managed section in exactly one place — immediately before the
``## Licence`` heading, or at the end of the file. Nothing else in the document
is read for meaning, reflowed, or reordered.
"""

