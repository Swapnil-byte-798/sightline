@dataclass(frozen=True, slots=True)
class Results:
    """Everything a full run produced."""

    selectivity: SelectivityReport
    attack: AttackReport
    reindex: ReindexCost
    mutation: MutationReport | None = None
    generated_at: float = field(default_factory=time.time)
    duration_s: float = 0.0


def collect(
    *,
    spec: CorpusSpec | None = None,
    skip_mutation: bool = False,
    mutation_timeout: float | None = None,
    progress: Any = None,
) -> Results:
    """Run the whole harness. Slow by design; this is the artefact CI publishes."""

    def say(line: str) -> None:
        if progress is not None:
            progress(line)

    started = time.perf_counter()
    say("selectivity: recall and cost versus permission density")
    selectivity = run_selectivity(spec, progress=progress)

    say("attack: the leak suite")
    attack = run_attacks(progress=progress)

    say("reindex: vector writes per permission change")
    reindex = measure_reindex_cost()

    mutation: MutationReport | None = None
    if not skip_mutation:
        say("mutation: 15 planted permission bugs, one suite run each")
        kwargs: dict[str, Any] = {"progress": progress}
        if mutation_timeout is not None:
            kwargs["timeout"] = mutation_timeout
        mutation = run_all(**kwargs)

    return Results(
        selectivity=selectivity,
        attack=attack,
        reindex=reindex,
        mutation=mutation,
        duration_s=time.perf_counter() - started,
    )


def _density_key(density: float) -> str:
    return f"{density:g}"


def metrics(results: Results) -> dict[str, float]:
    """Flatten a run into the gateable key/value pairs the README carries.

    Flat rather than nested because the drift report reads better as one line
    per key, and because a nested diff of two large dictionaries is how a changed
    number gets skimmed past.
    """
    out: dict[str, float] = {}

    if results.mutation is not None and not results.mutation.aborted:
        out["mutation.killed"] = len(results.mutation.killed)
        out["mutation.scored"] = len(results.mutation.scored)
        out["mutation.kill_rate"] = round(results.mutation.kill_rate, 4)

    out["attack.leaks"] = results.attack.leaks
    out["attack.passed"] = len(results.attack.results) - len(results.attack.failures) - len(
        results.attack.skipped
    )
    agreement = next(
        (r for r in results.attack.results if r.name == "plan_authority_agreement"), None
    )
    if agreement is not None:
        out["attack.false_allow"] = float(agreement.evidence.get("false_allow", -1))

    out["reindex.documents_retokenised_on_membership_change"] = (
        results.reindex.documents_retokenised_on_membership_change
    )
    out["reindex.documents_retokenised_on_acl_change"] = (
        results.reindex.documents_retokenised_on_acl_change
    )

    for density in results.selectivity.results:
        dk = _density_key(density.density)
        for arm in density.arms:
            out[f"selectivity.recall.{dk}.{arm.arm}"] = round(arm.recall_at_10, 4)
            out[f"selectivity.returned.{dk}.{arm.arm}"] = round(arm.mean_returned, 3)
            out[f"selectivity.cost.{dk}.{arm.arm}"] = arm.distance_computations
            # Latency is written, marked, and not gated. See the module docstring.
            out[f"{UNGATED_PREFIX}selectivity.p50_ms.{dk}.{arm.arm}"] = round(arm.p50_ms, 3)
    return out


