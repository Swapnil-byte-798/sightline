def _git_revision() -> str:
    try:
        proc = subprocess.run(
            ["git", "rev-parse", "--short", "HEAD"],
            cwd=str(REPO_ROOT), capture_output=True, text=True, check=False, timeout=10,
        )
    except (OSError, subprocess.SubprocessError):  # pragma: no cover - no git
        return "unknown"
    return proc.stdout.strip() or "unknown"


def _render_headline(results: Results) -> str:
    lines = ["## Measured results", ""]
    lines.append(
        "Every number below this line was produced by `python -m eval.report` and "
        "is re-derived by CI on each push. `python -m eval.report --check` fails "
        "the build if a committed figure no longer matches a fresh run. Nothing "
        "here is typed by hand."
    )
    lines.append("")
    if results.mutation is not None and not results.mutation.aborted:
        killed, scored = len(results.mutation.killed), len(results.mutation.scored)
        lines.append(
            f"* **Mutation kill rate: {killed}/{scored}** "
            f"({results.mutation.kill_rate:.0%}) against 15 pre-registered permission bugs."
        )
    else:
        lines.append(
            "* **Mutation kill rate: not measured in this run.** The harness was "
            "skipped or aborted; see the mutation section for why. A missing "
            "headline number is reported as missing, never as the last one we saw."
        )
    lines.append(
        f"* **Leaks: {results.attack.leaks}** across "
        f"{len(results.attack.results)} attacks mapped to the OWASP LLM Top 10."
    )
    lines.append(
        f"* **Vector writes per membership change: "
        f"{results.reindex.vectors_per_membership_change}** — measured by "
        f"comparing every document's compiled grant-token set across the write, "
        f"not by counting calls (ADR 0002). An ACL change on one document "
        f"retokenises "
        f"{results.reindex.documents_retokenised_on_acl_change} document(s), which "
        f"is the cost the design accepts."
    )
    lines.append(
        f"* **Post-filter recall at 10 bottoms out at "
        f"{results.selectivity.worst_post_filter_recall:.3f}** while scoring the "
        f"entire corpus. That collapse is the argument for compiling permissions "
        f"into the index, and it is published because it is the finding."
    )
    lines.append("")
    return "\n".join(lines)


def _render_provenance(results: Results, payload: dict[str, float]) -> str:
    selectivity = results.selectivity
    lines = ["### How these numbers were produced", ""]
    lines.append(
        f"Generated {time.strftime('%Y-%m-%d %H:%M:%S UTC', time.gmtime(results.generated_at))} "
        f"at `{_git_revision()}` on {platform.python_implementation()} "
        f"{platform.python_version()} / {platform.system()} {platform.machine()}, "
        f"in {results.duration_s:.0f}s."
    )
    lines.append("")
    lines.append(
        f"Corpus seed {selectivity.seed}, {selectivity.n_docs:,} documents, "
        f"{selectivity.n_queries} queries, embedder `{selectivity.embedder}`."
    )
    if not selectivity.semantic:
        lines.append("")
        lines.append(
            "**The embedder is not semantic.** It hashes word unigrams and "
            "bigrams, so every recall figure here is recall over string overlap. "
            "A previous repository of this author's published hash-embedder recall "
            "as semantic recall; the flag that prevents a repeat is "
            "`HashEmbedder.is_semantic`, checked here before anything is written."
        )
    lines.append("")
    lines.append(
        "Latency figures are written but **not gated**: this is a 2015 dual-core "
        "laptop and a build that fails when the machine is warm is a build "
        "everybody learns to ignore. Everything else is exact or carries the "
        "±0.02 tolerance from `docs/FRD.md` §8.3."
    )
    lines.append("")
    lines.append("Gated keys and their tolerances:")
    lines.append("")
    lines.append("| key | tolerance | why |")
    lines.append("|---|---:|---|")
    for gate in GATES:
        tolerance = "exact" if gate.tolerance == 0 else f"±{gate.tolerance:g}"
        lines.append(f"| `{gate.key}` | {tolerance} | {gate.why} |")
    lines.append("")
    lines.append(
        "The block below is the machine-readable copy `--check` compares against. "
        "It is a comment so it does not render, and it is in the document rather "
        "than in a side file so that a number and its provenance cannot be "
        "committed separately."
    )
    lines.append("")
    lines.append(_DATA_OPEN)
    lines.append(json.dumps(payload, indent=2, sort_keys=True))
    lines.append(_DATA_CLOSE)
    lines.append("")
    return "\n".join(lines)


def render_blocks(results: Results) -> dict[str, str]:
    """The rendered body of each managed region."""
    payload = metrics(results)
    mutation_body = (
        render_mutation(results.mutation)
        if results.mutation is not None
        else (
            "**Not measured in this run.** `python -m eval.report --skip-mutation` "
            "was used, which is a development convenience. CI never passes it, "
            "and a report produced with it carries no kill rate at all rather "
            "than the previous one.\n"
        )
    )
    return {
        "headline": _render_headline(results),
        "mutation": "### Mutation testing\n\n" + mutation_body,
        "selectivity": (
            "### Recall and cost versus permission density\n\n"
            + render_selectivity(results.selectivity)
        ),
        "attack": "### Attack suite\n\n" + render_attacks(results.attack),
        "provenance": _render_provenance(results, payload),
    }


# --------------------------------------------------------------------------
# README surgery
# --------------------------------------------------------------------------


def _block_re(name: str) -> re.Pattern[str]:
    return re.compile(
        re.escape(_BEGIN.format(name=name)) + r".*?" + re.escape(_END.format(name=name)),
        re.S,
    )


def _wrap(name: str, body: str) -> str:
    return f"{_BEGIN.format(name=name)}\n{body.rstrip()}\n{_END.format(name=name)}"


def write_readme(
    results: Results, *, path: Path = README, blocks: dict[str, str] | None = None
) -> bool:
    """Rewrite the managed regions in ``path``. Returns whether anything changed.

    Regions that are already present are replaced where they stand, so a
    maintainer who moves the mutation table above the selectivity table keeps
    that ordering. Regions that are absent are inserted together, once, just
    before ``## Licence`` — or appended if there is no such heading. Nothing
    outside the markers is touched.
    """
    rendered = blocks if blocks is not None else render_blocks(results)
    original = path.read_text(encoding="utf-8") if path.is_file() else "# Sightline\n"
    updated = original
    missing: list[str] = []

    for name in BLOCKS:
        pattern = _block_re(name)
        replacement = _wrap(name, rendered[name])
        if pattern.search(updated):
            updated = pattern.sub(lambda _m, r=replacement: r, updated, count=1)
        else:
            missing.append(name)

    if missing:
        section = "\n\n".join(_wrap(name, rendered[name]) for name in missing)
        licence = re.search(r"^## Licence\b", updated, re.M)
        if licence:
            at = licence.start()
            updated = updated[:at] + section + "\n\n" + updated[at:]
        else:
            updated = updated.rstrip() + "\n\n" + section + "\n"

    if updated == original:
        return False
    path.write_text(updated, encoding="utf-8")
    return True


def committed_metrics(path: Path = README) -> dict[str, float] | None:
    """Parse the machine-readable block out of the README, or ``None``."""
    if not path.is_file():
        return None
    match = _DATA_RE.search(path.read_text(encoding="utf-8"))
    if not match:
        return None
    try:
        blob = json.loads(match.group(1))
    except json.JSONDecodeError:
        return None
    return {str(k): float(v) for k, v in blob.items()} if isinstance(blob, dict) else None


def check_readme(fresh: dict[str, float], *, path: Path = README) -> list[Drift]:
    """Compare a fresh run against the committed block. Empty means no drift.

    A key present in one and not the other is drift, not an exception. Adding a
    metric is a change to what the README publishes and should go through the
    same gate as changing one; silently ignoring new keys is how a number gets
    added without anyone deciding it was true.
    """
    committed = committed_metrics(path)
    if committed is None:
        return [
            Drift(
                key="<readme>",
                committed=None,
                fresh=None,
                tolerance=0.0,
                why=(
                    f"no machine-readable block found in {path}. Run "
                    "`python -m eval.report` to generate it."
                ),
            )
        ]

    drifts: list[Drift] = []
    for key in sorted(set(committed) | set(fresh)):
        gate = gate_for(key)
        if gate is None:
            continue  # ungated, or not a metric this build makes claims about
        old = committed.get(key)
        new = fresh.get(key)
        if old is None or new is None:
            drifts.append(Drift(key, old, new, gate.tolerance, gate.why))
        elif abs(new - old) > gate.tolerance:
            drifts.append(Drift(key, old, new, gate.tolerance, gate.why))
    return drifts


