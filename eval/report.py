def main(argv: Sequence[str] | None = None) -> int:
    parser = argparse.ArgumentParser(
        prog="python -m eval.report",
        description="Generate every published number, write it into the README, or check it.",
    )
    parser.add_argument(
        "--check", action="store_true",
        help="do not write; exit non-zero if a committed number no longer matches",
    )
    parser.add_argument("--readme", type=Path, default=README)
    parser.add_argument(
        "--skip-mutation", action="store_true",
        help="development only. CI must not pass this: it removes the headline metric",
    )
    parser.add_argument("--docs", type=int, default=_SPEC_DEFAULTS.n_docs)
    parser.add_argument("--queries", type=int, default=_SPEC_DEFAULTS.n_queries)
    parser.add_argument("--seed", type=int, default=_SPEC_DEFAULTS.seed)
    parser.add_argument("--mutation-timeout", type=float, default=None)
    parser.add_argument("--json", type=Path, default=None, help="also write the raw run here")
    parser.add_argument("--quiet", action="store_true")
    args = parser.parse_args(argv)

    def say(line: str) -> None:
        if not args.quiet:
            print(line, file=sys.stderr)

    spec = CorpusSpec(n_docs=args.docs, n_queries=args.queries, seed=args.seed)
    results = collect(
        spec=spec,
        skip_mutation=args.skip_mutation,
        mutation_timeout=args.mutation_timeout,
        progress=None if args.quiet else say,
    )
    fresh = metrics(results)

    if args.json is not None:
        args.json.write_text(
            json.dumps(
                {
                    "metrics": fresh,
                    "selectivity": results.selectivity.to_dict(),
                    "attack": results.attack.to_dict(),
                    "mutation": results.mutation.to_dict() if results.mutation else None,
                },
                indent=2,
                sort_keys=True,
            ),
            encoding="utf-8",
        )

    if args.check:
        drifts = check_readme(fresh, path=args.readme)
        if args.skip_mutation:
            say(
                "warning: --skip-mutation was passed, so the headline metric was "
                "not re-derived and is not being checked. This is not a valid CI "
                "invocation."
            )
        if not drifts:
            gated = sum(1 for k in fresh if gate_for(k) is not None)
            print(f"{gated} gated number(s) match the README.")
            return 0
        print(f"{len(drifts)} number(s) drifted from the README:", file=sys.stderr)
        for drift in drifts:
            print(f"  {drift}", file=sys.stderr)
        print(
            "\nA drifting number is a failing build, not a stale document. Either "
            "the code changed and `python -m eval.report` should be re-run and the "
            "result committed, or the change was not intended.",
            file=sys.stderr,
        )
        return 1

    changed = write_readme(results, path=args.readme)
    print(f"{args.readme}: {'updated' if changed else 'already up to date'}")
    return 0


if __name__ == "__main__":  # pragma: no cover - entry point
    raise SystemExit(main())
