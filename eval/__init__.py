"""The evaluation harness: the part of this repo that is allowed to disagree
with the rest of it.

Four modules, in the order you should read them:

1. :mod:`eval.selectivity` — recall and cost as a function of how much of the
   corpus a principal can see. The headline *chart*. Post-filtering (the
   deliberately-wrong baseline arm) is expected to collapse as the visible
   fraction shrinks; the number is published because the collapse is the
   argument for pushing the filter into the index.
2. :mod:`eval.mutation` — fifteen pre-registered permission bugs, applied one at
   a time to a throwaway copy of the source tree, with the test suite run against
   each. The headline *metric*: the kill rate.
3. :mod:`eval.attack` — the leak suite. Cross-principal ground truth, existence
   probing, injection through retrieved documents, revocation races, timing
   enumeration. Each entry maps to an OWASP LLM Top 10 item.
4. :mod:`eval.report` — writes every number into ``README.md`` between
   machine-managed markers, and ``--check`` fails the build when a committed
   number no longer matches a fresh run.

THE RULE THIS PACKAGE ENFORCES ON ITSELF
----------------------------------------
Nothing here is allowed to publish a number it did not just compute. A figure
typed into a README by hand is a claim; a figure regenerated by CI and diffed
against the committed one is a measurement. ``eval.report --check`` is the
difference, and it is the only reason the numbers in this repository are worth
reading.

Two honesty guards live here rather than in prose:

* :data:`eval.selectivity.RECALL_FLOOR` is a **floor**, never an equality.
  Approximate indexes are approximate; ``filtered top-k == exact top-k`` is true
  only when the query routes to brute force, and asserting it anywhere else is a
  test that will eventually lie.
* Any result computed with
  :class:`~sightline.ingest.embed.HashEmbedder` is stamped
  ``semantic=false``. That embedder hashes words; it has never seen a sentence.
  Publishing its recall as semantic recall is a mistake this author has made
  before, and it is why the flag exists on the embedder at all.

Running the harness needs the package on the path. ``sightline`` is not
installed into the development virtualenv here, so importing :mod:`eval` from
the repository root inserts ``src/`` for you rather than making every entry
point start with a ``PYTHONPATH=`` incantation people get wrong.
"""

from __future__ import annotations

import sys
from pathlib import Path

#: Repository root — the directory holding ``src/``, ``eval/`` and ``README.md``.
REPO_ROOT = Path(__file__).resolve().parent.parent

#: Where the package source lives. Inserted on ``sys.path`` below if needed.
SRC_ROOT = REPO_ROOT / "src"


def _ensure_importable() -> None:
    """Put ``src/`` on the path when ``sightline`` is not installed.

    Deliberately conditional: if somebody has done ``pip install -e .``, their
    installed copy wins and this does nothing. Prepending unconditionally would
    mean the harness silently measured the working tree while CI measured the
    wheel, and a benchmark that measures a different build than the one you ship
    is worse than no benchmark.
    """
    try:  # pragma: no cover - trivial, and exercised by every other import here
        import sightline  # noqa: F401
    except ImportError:
        if SRC_ROOT.is_dir():
            sys.path.insert(0, str(SRC_ROOT))


_ensure_importable()

__all__ = ["REPO_ROOT", "SRC_ROOT"]
